"""Known names of 卫戍协议·规程: OCR text → the name it stands for.

``resources/data/prts_lists.json`` (generated by ``private/tools/gen_prts_lists.py`` from the
PRTS wiki) lists the strategies, operators (with stand-in bodies), faction bonds (阵营),
trait bonds (特性) and equipment. The names in ``sp3_operators.json`` are added, so the
tactics' table and the matcher never disagree.

OCR adds noise in front of names: the profession icon left of a card or held-panel name is
read as a character (医疗 → 「水」「冰」, 近卫 → 「入」, 狙击 → 「N」, …) and bond icons
as 「X」「派」「太」. A read is matched in this order:

1. exact name;
2. the read minus one or two leading characters is a name (「水褐果」 → 褐果; 「水月」 stays 水月);
3. exactly one known name inside the read (longest wins: 「入空无法购买」 → 空);
4. edit distance: one wrong character for names of 2–3 characters, two for longer ones,
   only when a single name is that close (「青积」 → 青枳).
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Iterable, Sequence

from ..paths import resource

# Toasts drawn over card names / panels; never part of a name.
NOISE_WORDS = ("无法购买", "资金不足", "整备区已满", "干员已满")
_STRIP = re.compile(r"[\s，,。、:：;；'\"“”‘’!！?？*△▲□■◇◆○●·`~|]")


@dataclass(frozen=True)
class Match:
    name: str            # the known name, or the cleaned read when nothing matched
    score: float         # 1.0 exact … 0.0 unknown
    kind: str = ""       # "operator" | "stand_in" | "equipment" | "bond" | "strategy" | ""

    @property
    def known(self) -> bool:
        return self.score > 0


def clean(text: str) -> str:
    t = text or ""
    for w in NOISE_WORDS:
        t = t.replace(w, "")
    # keep 「领主·Sharp」, 「Miss.Christine」: a middle dot between characters stays
    t = t.strip(".")
    return _STRIP.sub(lambda m: m.group(0) if m.group(0) == "·" and 0 < m.start() < len(t) - 1 else "", t)


def distance(a: str, b: str) -> int:
    """Levenshtein distance."""
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


class NameSet:
    """One family of names (operators, equipment, bonds …) with the matching rules above."""

    def __init__(self, names: Iterable[str], kinds: dict[str, str] | None = None):
        self.names = sorted({n for n in names if n}, key=len, reverse=True)
        self._set = set(self.names)
        self.kinds = kinds or {}

    def __contains__(self, name: str) -> bool:
        return name in self._set

    def _match(self, name: str, score: float) -> Match:
        return Match(name, score, self.kinds.get(name, ""))

    def match(self, text: str) -> Match:
        t = clean(text)
        if not t:
            return Match("", 0.0)
        if t in self._set:
            return self._match(t, 1.0)
        for k in (1, 2):
            if len(t) - k >= 1 and t[k:] in self._set:
                return self._match(t[k:], 0.9)
        inside = [n for n in self.names if n in t]
        inside = [n for n in inside if not any(n != o and n in o for o in inside)]
        if len(inside) == 1 and len(inside[0]) >= 2:
            return self._match(inside[0], 0.8)
        best: list[tuple[int, str]] = []
        for n in self.names:
            if abs(len(n) - len(t)) > 2:
                continue
            d = min([distance(t, n)] + [distance(t[k:], n) for k in (1, 2) if len(t) > k])
            if d <= (1 if len(n) <= 3 else 2) and d < len(n):
                best.append((d, n))
        best.sort()
        if best and (len(best) == 1 or best[0][0] < best[1][0]):
            d, n = best[0]
            return self._match(n, 0.7 - 0.1 * d)
        return Match(t, 0.0)

    def all_in(self, text: str) -> list[str]:
        """Every name found in ``text`` (two labels read as one line: 「谢拉格协防干员」)."""
        t = clean(text)
        hit = self.match(t)
        if hit.score >= 0.9:
            return [hit.name]
        found = [n for n in self.names if n in t]
        found = [n for n in found if not any(n != o and n in o for o in found)]
        if found:
            return sorted(found, key=t.index)
        return [hit.name] if hit.known else []


class Names:
    def __init__(self, data: dict, extra_operators: Iterable[str] = (), extra_stand_ins: Iterable[str] = ()):
        operators = [o["name"] for o in data.get("operators", [])] + list(extra_operators)
        stand_ins = list(data.get("stand_ins", [])) + list(extra_stand_ins)
        kinds = {n: "operator" for n in operators}
        kinds.update({n: "stand_in" for n in stand_ins})
        self.tiers: dict[str, int] = {o["name"]: int(o.get("tier", 0)) for o in data.get("operators", [])}
        self.operators = NameSet(operators + stand_ins, kinds)
        self.equipment = NameSet(e["name"] for e in data.get("equipment", []))
        self.factions = list(data.get("factions", []))
        self.traits = list(data.get("traits", []))
        self.bonds = NameSet(self.factions + self.traits)
        self.strategies = NameSet(s["name"] for s in data.get("strategies", []))
        self.leaders = NameSet(s["leader"] for s in data.get("strategies", []))   # shown on strategy cards

    @classmethod
    def load(cls) -> "Names":
        return _load(str(resource("data", "prts_lists.json")), str(resource("data", "sp3_operators.json")))

    def operator(self, text: str) -> Match:
        """A card / held-panel name. Equipment names are never taken for operators."""
        t = clean(text)
        if t in self.equipment:
            return Match(t, 1.0, "equipment")
        hit = self.operators.match(t)
        if hit.score < 0.9:
            gear = self.equipment.match(t)
            if gear.score > hit.score:
                return Match(gear.name, gear.score, "equipment")
        return hit

    def is_equipment(self, text: str) -> bool:
        return self.operator(text).kind == "equipment"

    def labels(self, texts: Sequence[str]) -> list[str]:
        """Bond labels read from a card or the held panel, cleaned; unreadable ones dropped."""
        out: list[str] = []
        for text in texts:
            for b in self.bonds.all_in(text):
                if b not in out:
                    out.append(b)
        return out


@lru_cache(maxsize=2)
def _load(lists: str, table: str) -> Names:
    data = json.loads(Path(lists).read_text(encoding="utf-8")) if Path(lists).exists() else {}
    extra_ops: list[str] = []
    extra_stand: list[str] = []
    if Path(table).exists():
        t = json.loads(Path(table).read_text(encoding="utf-8"))
        extra_ops = list(t.get("operators", {}))
        extra_stand = list(t.get("stand_ins", {}))
    return Names(data, extra_ops, extra_stand)
